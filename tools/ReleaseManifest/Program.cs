using System.Diagnostics;
using System.Globalization;
using System.Reflection.Metadata;
using System.Reflection.PortableExecutable;
using System.Security.Cryptography;
using System.Text;

namespace PatentMarker.ReleaseManifest;

internal static class Program
{
    private static int Main(string[] args)
    {
        if (args.Length == 0)
        {
            Usage();
            return 2;
        }
        try
        {
            return args[0] switch
            {
                "generate" => Generate(args.Skip(1).ToArray()),
                "verify" => Verify(args.Skip(1).ToArray()),
                "inspect" => Inspect(args.Skip(1).ToArray()),
                _ => Unknown(args[0])
            };
        }
        catch (Exception ex)
        {
            Console.Error.WriteLine("ERROR: " + ex.Message);
            return 1;
        }
    }

    private static int Generate(string[] args)
    {
        if (args.Length < 2)
        {
            Console.Error.WriteLine("Usage: ReleaseManifest generate <artifact.dll> <manifest.txt> [options]");
            return 2;
        }
        string artifact = Path.GetFullPath(args[0]);
        string output = Path.GetFullPath(args[1]);
        Dictionary<string, string> options = ParseOptions(args.Skip(2));
        ArtifactIdentity identity = ArtifactIdentity.Read(artifact);
        string product = Get(options, "product", "PatentMarker");
        string edition = Get(options, "edition", "");
        string productVersion = Get(options, "version", identity.InformationalVersion);
        string sourceCommit = Get(options, "source-commit", Git("rev-parse HEAD"));
        string sourceTree = Get(options, "source-tree", "");
        if (string.IsNullOrEmpty(sourceTree))
        {
            sourceTree = string.IsNullOrEmpty(sourceCommit)
                ? Git("rev-parse HEAD^{tree}")
                : Git("rev-parse " + sourceCommit + "^{tree}");
        }
        string sourceDirty = Get(options, "source-dirty", GitDirty());
        string sourceState = Get(options, "source-state", sourceDirty == "true" ? "dirty-worktree" : "clean-commit");
        string sourceNote = Get(options, "source-note", "");
        string buildTool = Get(options, "build-tool", "");
        string buildCommand = Get(options, "build-command", "");
        string generatedUtc = Get(options, "generated-utc", DateTime.UtcNow.ToString("yyyy-MM-ddTHH:mm:ssZ", CultureInfo.InvariantCulture));

        var lines = new List<string>
        {
            "# PatentMarker release manifest. Generated by tools/ReleaseManifest. Do not edit by hand.",
            "format=1",
            "product=" + product,
            "edition=" + edition,
            "version=" + productVersion,
            "source.commit=" + sourceCommit,
            "source.tree=" + sourceTree,
            "source.dirty=" + sourceDirty,
            "source.state=" + sourceState,
            "source.note=" + OneLine(sourceNote),
            "build.tool=" + OneLine(buildTool),
            "build.command=" + OneLine(buildCommand),
            "generated_utc=" + generatedUtc,
            "artifact.file=" + identity.FileName,
            "artifact.size=" + identity.Size.ToString(CultureInfo.InvariantCulture),
            "artifact.sha256=" + identity.Sha256,
            "artifact.mvid=" + identity.Mvid,
            "artifact.assembly_version=" + identity.AssemblyVersion,
            "artifact.informational_version=" + identity.InformationalVersion,
            "artifact.types=" + identity.TypeCount.ToString(CultureInfo.InvariantCulture),
            "artifact.methods=" + identity.MethodCount.ToString(CultureInfo.InvariantCulture)
        };

        AddOptionalFile(lines, "pdb", "pdb.sha256", Get(options, "pdb", ""));
        AddOptionalFile(lines, "dotm", "assets.dotm.sha256", Get(options, "dotm", ""));
        string vbaDir = Get(options, "vba-dir", "");
        if (!string.IsNullOrEmpty(vbaDir))
        {
            string vbaManifestHash = HashDirectoryManifest(vbaDir);
            lines.Add("assets.vba.files_sha256=" + vbaManifestHash);
        }

        Directory.CreateDirectory(Path.GetDirectoryName(output)!);
        File.WriteAllText(output, string.Join("\n", lines) + "\n", new UTF8Encoding(false));
        Console.WriteLine("WROTE " + output);
        Console.WriteLine("artifact.sha256=" + identity.Sha256);
        Console.WriteLine("artifact.mvid=" + identity.Mvid);
        return 0;
    }

    private static int Verify(string[] args)
    {
        if (args.Length < 2)
        {
            Console.Error.WriteLine("Usage: ReleaseManifest verify <manifest.txt> <artifact.dll> [--dotm file] [--vba-dir dir]");
            return 2;
        }
        string manifestPath = Path.GetFullPath(args[0]);
        string artifact = Path.GetFullPath(args[1]);
        Dictionary<string, string> options = ParseOptions(args.Skip(2));
        Dictionary<string, string> values = ReadManifest(manifestPath);
        ArtifactIdentity identity = ArtifactIdentity.Read(artifact);
        List<string> errors = new();
        Require(values, "format", "1", errors);
        Require(values, "artifact.file", identity.FileName, errors);
        Require(values, "artifact.size", identity.Size.ToString(CultureInfo.InvariantCulture), errors);
        Require(values, "artifact.sha256", identity.Sha256, errors);
        Require(values, "artifact.mvid", identity.Mvid, errors);
        string expectedInfo = Get(values, "artifact.informational_version", "");
        if (expectedInfo.Length > 0 && !string.Equals(expectedInfo, identity.InformationalVersion, StringComparison.Ordinal))
            errors.Add("informational_version expected=" + expectedInfo + " actual=" + identity.InformationalVersion);
        VerifyOptionalAsset(values, options, "dotm", "assets.dotm.sha256", errors);
        string vbaDir = Get(options, "vba-dir", "");
        if (!string.IsNullOrEmpty(vbaDir))
        {
            string expected = Get(values, "assets.vba.files_sha256", "");
            string actual = HashDirectoryManifest(vbaDir);
            if (expected.Length == 0 || !string.Equals(expected, actual, StringComparison.OrdinalIgnoreCase))
                errors.Add("assets.vba.files_sha256 expected=" + expected + " actual=" + actual);
        }
        if (errors.Count == 0)
        {
            Console.WriteLine("PASS manifest=" + manifestPath);
            Console.WriteLine("artifact=" + artifact);
            Console.WriteLine("sha256=" + identity.Sha256);
            Console.WriteLine("mvid=" + identity.Mvid);
            return 0;
        }
        Console.Error.WriteLine("FAIL manifest=" + manifestPath);
        foreach (string error in errors) Console.Error.WriteLine(" - " + error);
        return 1;
    }

    private static void VerifyOptionalAsset(
        Dictionary<string, string> values,
        Dictionary<string, string> options,
        string optionName,
        string manifestKey,
        List<string> errors)
    {
        string path = Get(options, optionName, "");
        if (string.IsNullOrEmpty(path)) return;
        string expected = Get(values, manifestKey, "");
        string actual = Convert.ToHexString(SHA256.HashData(File.ReadAllBytes(Path.GetFullPath(path)))).ToLowerInvariant();
        if (expected.Length == 0 || !string.Equals(expected, actual, StringComparison.OrdinalIgnoreCase))
            errors.Add(manifestKey + " expected=" + expected + " actual=" + actual);
    }

    private static int Inspect(string[] args)
    {
        if (args.Length != 1)
        {
            Console.Error.WriteLine("Usage: ReleaseManifest inspect <artifact.dll>");
            return 2;
        }
        ArtifactIdentity identity = ArtifactIdentity.Read(Path.GetFullPath(args[0]));
        Console.WriteLine("file=" + identity.FileName);
        Console.WriteLine("size=" + identity.Size);
        Console.WriteLine("sha256=" + identity.Sha256);
        Console.WriteLine("mvid=" + identity.Mvid);
        Console.WriteLine("assembly_version=" + identity.AssemblyVersion);
        Console.WriteLine("informational_version=" + identity.InformationalVersion);
        Console.WriteLine("types=" + identity.TypeCount);
        Console.WriteLine("methods=" + identity.MethodCount);
        return 0;
    }

    private sealed class ArtifactIdentity
    {
        public required string FileName { get; init; }
        public required long Size { get; init; }
        public required string Sha256 { get; init; }
        public required string Mvid { get; init; }
        public required string AssemblyVersion { get; init; }
        public required string InformationalVersion { get; init; }
        public required int TypeCount { get; init; }
        public required int MethodCount { get; init; }

        public static ArtifactIdentity Read(string path)
        {
            byte[] bytes = File.ReadAllBytes(path);
            using var pe = new PEReader(new MemoryStream(bytes, writable: false));
            if (!pe.HasMetadata) throw new InvalidDataException("Not a managed PE image: " + path);
            MetadataReader reader = pe.GetMetadataReader();
            int methods = 0;
            foreach (TypeDefinitionHandle typeHandle in reader.TypeDefinitions)
                methods += reader.GetTypeDefinition(typeHandle).GetMethods().Count;
            string assemblyVersion = reader.IsAssembly
                ? reader.GetAssemblyDefinition().Version.ToString()
                : "";
            return new ArtifactIdentity
            {
                FileName = Path.GetFileName(path),
                Size = bytes.LongLength,
                Sha256 = Convert.ToHexString(SHA256.HashData(bytes)).ToLowerInvariant(),
                Mvid = reader.GetGuid(reader.GetModuleDefinition().Mvid).ToString("D"),
                AssemblyVersion = assemblyVersion,
                InformationalVersion = ReadInformationalVersion(reader),
                TypeCount = reader.TypeDefinitions.Count,
                MethodCount = methods
            };
        }
    }

    private static string ReadInformationalVersion(MetadataReader reader)
    {
        if (!reader.IsAssembly) return "";
        foreach (CustomAttributeHandle handle in reader.GetAssemblyDefinition().GetCustomAttributes())
        {
            CustomAttribute attr = reader.GetCustomAttribute(handle);
            if (attr.Constructor.Kind != HandleKind.MemberReference) continue;
            MemberReference ctor = reader.GetMemberReference((MemberReferenceHandle)attr.Constructor);
            if (ctor.Parent.Kind != HandleKind.TypeReference) continue;
            TypeReference parent = reader.GetTypeReference((TypeReferenceHandle)ctor.Parent);
            if (reader.GetString(parent.Namespace) != "System.Reflection") continue;
            if (reader.GetString(parent.Name) != "AssemblyInformationalVersionAttribute") continue;
            BlobReader blob = reader.GetBlobReader(attr.Value);
            if (blob.ReadUInt16() != 1) continue;
            return blob.ReadSerializedString() ?? "";
        }
        return "";
    }

    private static void AddOptionalFile(List<string> lines, string label, string key, string path)
    {
        if (string.IsNullOrEmpty(path)) return;
        string full = Path.GetFullPath(path);
        if (!File.Exists(full)) throw new FileNotFoundException(label + " not found", full);
        lines.Add(key + "=" + Convert.ToHexString(SHA256.HashData(File.ReadAllBytes(full))).ToLowerInvariant());
    }

    private static string HashDirectoryManifest(string dir)
    {
        string full = Path.GetFullPath(dir);
        if (!Directory.Exists(full)) throw new DirectoryNotFoundException(full);
        var entries = Directory.GetFiles(full, "*", SearchOption.AllDirectories)
            .OrderBy(x => Path.GetRelativePath(full, x), StringComparer.Ordinal)
            .Select(x => Path.GetRelativePath(full, x).Replace('\\', '/') + "="
                + Convert.ToHexString(SHA256.HashData(File.ReadAllBytes(x))).ToLowerInvariant());
        return Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(string.Join("\n", entries)))).ToLowerInvariant();
    }

    private static Dictionary<string, string> ReadManifest(string path)
    {
        var values = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase);
        foreach (string raw in File.ReadAllLines(path))
        {
            string line = raw.Trim();
            if (line.Length == 0 || line.StartsWith("#", StringComparison.Ordinal)) continue;
            int index = line.IndexOf('=');
            if (index <= 0) continue;
            values[line[..index].Trim()] = line[(index + 1)..].Trim();
        }
        return values;
    }

    private static void Require(Dictionary<string, string> values, string key, string expected, List<string> errors)
    {
        string actual = Get(values, key, "");
        if (!string.Equals(actual, expected, StringComparison.OrdinalIgnoreCase))
            errors.Add(key + " expected=" + expected + " actual=" + actual);
    }

    private static Dictionary<string, string> ParseOptions(IEnumerable<string> args)
    {
        var values = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase);
        string? pending = null;
        foreach (string arg in args)
        {
            if (arg.StartsWith("--", StringComparison.Ordinal))
            {
                if (pending != null) values[pending] = "true";
                pending = arg[2..];
            }
            else if (pending != null)
            {
                values[pending] = arg;
                pending = null;
            }
            else
            {
                throw new ArgumentException("Unexpected option value: " + arg);
            }
        }
        if (pending != null) values[pending] = "true";
        return values;
    }

    private static string Get(Dictionary<string, string> values, string key, string fallback) =>
        values.TryGetValue(key, out string? value) && !string.IsNullOrEmpty(value) ? value : fallback;

    private static string OneLine(string value) => value.Replace("\r", " ").Replace("\n", " ").Trim();

    private static string Git(string arguments)
    {
        try
        {
            using Process process = Process.Start(new ProcessStartInfo
            {
                FileName = "git",
                Arguments = arguments,
                RedirectStandardOutput = true,
                RedirectStandardError = true,
                UseShellExecute = false,
                CreateNoWindow = true
            })!;
            string output = process.StandardOutput.ReadToEnd().Trim();
            process.WaitForExit(5000);
            return process.ExitCode == 0 ? output : "";
        }
        catch { return ""; }
    }

    private static string GitDirty()
    {
        try
        {
            using Process process = Process.Start(new ProcessStartInfo
            {
                FileName = "git",
                Arguments = "status --porcelain --untracked-files=normal",
                RedirectStandardOutput = true,
                RedirectStandardError = true,
                UseShellExecute = false,
                CreateNoWindow = true
            })!;
            string output = process.StandardOutput.ReadToEnd();
            process.WaitForExit(5000);
            return process.ExitCode == 0 && output.Trim().Length == 0 ? "false" : "true";
        }
        catch { return "unknown"; }
    }

    private static int Unknown(string command)
    {
        Console.Error.WriteLine("Unknown command: " + command);
        Usage();
        return 2;
    }

    private static void Usage()
    {
        Console.Error.WriteLine("Usage:");
        Console.Error.WriteLine("  ReleaseManifest inspect <artifact.dll>");
        Console.Error.WriteLine("  ReleaseManifest generate <artifact.dll> <manifest.txt> [--edition 2025] [--version 1.0.0] [--pdb file] [--dotm file] [--vba-dir dir] [--source-commit sha] [--source-dirty true|false] [--source-note text] [--build-tool text] [--build-command text]");
        Console.Error.WriteLine("  ReleaseManifest verify <manifest.txt> <artifact.dll>");
    }
}
